import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const company = id(1), otherCompany = id(2), driver = id(3), otherDriver = id(4), admin = id(5), foreignAdmin = id(6), vehicle = id(7), assignment = id(8);
await db.exec(`
  CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
  CREATE SCHEMA auth;
  CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('test.uid',true),'')::uuid $$;
  CREATE TYPE public.app_role AS ENUM ('admin','driver');
  CREATE TABLE companies(id uuid PRIMARY KEY);
  CREATE TABLE profiles(id uuid PRIMARY KEY,company_id uuid);
  CREATE TABLE user_roles(user_id uuid,company_id uuid,role public.app_role);
  CREATE TABLE vehicles(id uuid PRIMARY KEY,company_id uuid);
  CREATE TABLE assignments(id uuid PRIMARY KEY,company_id uuid,vehicle_id uuid,assigned_driver_id uuid,status text,actual_start timestamptz,actual_stop timestamptz);
  CREATE FUNCTION public.get_my_company_id() RETURNS uuid LANGUAGE sql SECURITY DEFINER SET search_path='' AS $$ SELECT company_id FROM public.profiles WHERE id=auth.uid() $$;
  CREATE FUNCTION public.has_role(uid uuid,r public.app_role) RETURNS boolean LANGUAGE sql SECURITY DEFINER SET search_path='' AS $$ SELECT EXISTS(SELECT 1 FROM public.user_roles WHERE user_id=uid AND role=r AND company_id=public.get_my_company_id()) $$;
  INSERT INTO companies VALUES('${company}'),('${otherCompany}');
  INSERT INTO profiles VALUES('${driver}','${company}'),('${otherDriver}','${company}'),('${admin}','${company}'),('${foreignAdmin}','${otherCompany}');
  INSERT INTO user_roles VALUES('${driver}','${company}','driver'),('${otherDriver}','${company}','driver'),('${admin}','${company}','admin'),('${foreignAdmin}','${otherCompany}','admin');
  INSERT INTO vehicles VALUES('${vehicle}','${company}'),('${id(9)}','${otherCompany}');
  INSERT INTO assignments VALUES('${assignment}','${company}','${vehicle}','${driver}','pending',NULL,NULL);
  GRANT USAGE ON SCHEMA public,auth TO authenticated,anon;
`);
await db.exec(await readFile('drizzle/migrations/0000_vehicle_pre_drive_checks.sql','utf8'));
await db.exec(await readFile('drizzle/migrations/0001_vehicle_checks_explicit_privileges.sql','utf8'));
const login = async uid => { await db.exec('RESET ROLE'); await db.query("SELECT set_config('test.uid',$1,false)",[uid ?? '']); await db.exec('SET ROLE authenticated'); };
const report = (op, tires='no_issue', lights='no_issue', damage='no_issue', critical=false, note='') => db.query('SELECT * FROM public.report_vehicle_check($1,$2,$3,$4,$5,$6,$7)',[op,assignment,tires,lights,damage,critical,note]);
await login(driver);
await report(id(10));
assert.equal((await db.query('SELECT * FROM vehicle_checks')).rows.length,1);
assert.equal((await report(id(10))).rows[0].id,id(10));
assert.equal((await db.query('SELECT * FROM vehicle_checks')).rows.length,1, 'retry does not duplicate history');
await assert.rejects(report(id(10),'issue','no_issue','no_issue',false,'different'),/nyckeln/);
await assert.rejects(report(id(11),'not_checked'),/alla punkter/);
await assert.rejects(report(id(11),'issue'),/Beskriv/);
const critical = (await report(id(11),'not_checked','not_checked','not_checked',true,'Bromsskada')).rows[0];
assert.equal(critical.status,'open'); assert.equal(critical.safety_critical,true);
await assert.rejects(db.query("INSERT INTO vehicle_checks(id) VALUES($1)",[id(12)]),/permission denied/);
await assert.rejects(db.exec("UPDATE vehicle_checks SET note='forged'"),/permission denied/);
await assert.rejects(db.exec('DELETE FROM vehicle_checks'),/permission denied/);
await assert.rejects(db.query('SELECT resolve_vehicle_check($1,$2)',[id(11),'Reparerat']),/administratören/);
await login(otherDriver);
assert.equal((await db.query('SELECT * FROM vehicle_checks')).rows.length,0,'other drivers cannot read the reporter history');
await assert.rejects(report(id(12)),/tillgång/);
await login(foreignAdmin);
assert.equal((await db.query('SELECT * FROM vehicle_checks')).rows.length,0,'cross-company reads denied');
await assert.rejects(report(id(12)),/tillgång/);
await assert.rejects(db.query('SELECT resolve_vehicle_check($1,$2)',[id(11),'Reparerat']),/hittades inte/);
await login(admin);
assert.equal((await db.query('SELECT * FROM vehicle_checks')).rows.length,2,'company administrator sees reports');
await assert.rejects(db.query('SELECT resolve_vehicle_check($1,$2)',[id(11),' ']),/Beskriv/);
const resolved = (await db.query('SELECT * FROM resolve_vehicle_check($1,$2)',[id(11),'Bromsslang bytt'])).rows[0];
assert.equal(resolved.status,'resolved'); assert.equal(resolved.note,'Bromsskada'); assert.equal(resolved.resolved_by,admin);
await assert.rejects(db.query('SELECT resolve_vehicle_check($1,$2)',[id(11),'Again']),/redan avslutad/);

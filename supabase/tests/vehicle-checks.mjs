await login(driver); await assert.rejects(report(id(12)),/tillgång/);
await db.exec('RESET ROLE; SET ROLE anon');
await assert.rejects(db.query('SELECT * FROM vehicle_checks'),/permission denied/);
await assert.rejects(report(id(12)),/permission denied/);
await db.close();
